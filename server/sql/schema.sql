-- -------------------------------------------------
-- Tabel users: menyimpan akun admin & customer
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  email varchar(150) NOT NULL UNIQUE,          -- selalu disimpan huruf kecil
  password varchar(255) NOT NULL,              -- hash bcrypt, bukan password asli
  phone varchar(30),
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'customer')),
  password_changed_at timestamptz,             -- token login sebelum waktu ini ditolak
  created_at timestamptz NOT NULL DEFAULT now()
);

-- -------------------------------------------------
-- Tabel reservations: menyimpan data booking
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reservations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  customer_name varchar(150) NOT NULL,
  whatsapp varchar(30) NOT NULL,
  service_name varchar(150) NOT NULL,
  reservation_date date NOT NULL,
  reservation_time time NOT NULL,
  end_time time,
  notes text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'confirmed', 'cancelled', 'done')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Mempercepat cek slot kosong & daftar "Reservasi Saya"
CREATE INDEX IF NOT EXISTS idx_reservations_slot
  ON public.reservations (reservation_date, reservation_time, status);
CREATE INDEX IF NOT EXISTS idx_reservations_user ON public.reservations (user_id);

-- -------------------------------------------------
-- Tabel testimonials: ulasan dari customer yang login
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.testimonials (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_testimonials_user ON public.testimonials (user_id);

-- -------------------------------------------------
-- Tabel password_resets: token link "Lupa Password" (berlaku 30 menit, sekali pakai)
-- Yang disimpan hanya hash SHA-256 dari token, bukan token aslinya.
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.password_resets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_password_resets_user ON public.password_resets (user_id);

-- -------------------------------------------------
-- Tabel payments: satu baris = satu transaksi di kasir (Cash / QRIS)
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_no varchar(30) NOT NULL UNIQUE,                -- contoh: INV-20261104-0001
  reservation_id integer REFERENCES public.reservations(id) ON DELETE SET NULL,
  user_id integer REFERENCES public.users(id) ON DELETE SET NULL,   -- akun customer (kalau ada)
  cashier_id integer REFERENCES public.users(id) ON DELETE SET NULL, -- admin yang melayani
  source text NOT NULL CHECK (source IN ('booking', 'walkin')),
  customer_name varchar(150) NOT NULL,
  whatsapp varchar(30),
  subtotal integer NOT NULL CHECK (subtotal >= 0),
  discount integer NOT NULL DEFAULT 0 CHECK (discount >= 0),
  total integer NOT NULL CHECK (total >= 0),
  method text NOT NULL CHECK (method IN ('cash', 'qris')),
  cash_received integer,
  change_amount integer,
  notes text,
  status text NOT NULL DEFAULT 'paid' CHECK (status IN ('paid', 'void')),
  void_reason text,
  voided_at timestamptz,
  paid_at timestamptz NOT NULL DEFAULT now(),
  CHECK (total = subtotal - discount)
);

-- Satu reservasi hanya boleh punya satu pembayaran yang masih berlaku
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_reservation_paid
  ON public.payments (reservation_id) WHERE status = 'paid';
CREATE INDEX IF NOT EXISTS idx_payments_paid_at ON public.payments (paid_at);
CREATE INDEX IF NOT EXISTS idx_payments_user ON public.payments (user_id);

-- -------------------------------------------------
-- Tabel payment_items: rincian layanan per transaksi (nama & harga disalin
-- saat transaksi, supaya struk lama tetap benar walau pricelist berubah)
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payment_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id integer NOT NULL REFERENCES public.payments(id) ON DELETE CASCADE,
  service_name varchar(150) NOT NULL,
  price integer NOT NULL CHECK (price >= 0),
  qty smallint NOT NULL CHECK (qty BETWEEN 1 AND 20),
  subtotal integer NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX IF NOT EXISTS idx_payment_items_payment ON public.payment_items (payment_id);

-- -------------------------------------------------
-- Tabel settings: pengaturan salon (key-value), mis. gambar QRIS
-- -------------------------------------------------
CREATE TABLE IF NOT EXISTS public.settings (
  key varchar(50) PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- -------------------------------------------------
-- Keamanan: aktifkan Row Level Security TANPA policy.
-- Artinya tabel TIDAK bisa diakses lewat API publik Supabase (anon key),
-- hanya lewat backend Express yang konek langsung ke database.
-- Tanpa ini, data user (termasuk hash password) bisa dibaca siapa saja.
-- -------------------------------------------------
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.testimonials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;

